# ---------------------------------------------------------------- Swift output

def swift_string_list(rows, indent):
    pad = " " * indent
    return "[\n" + "".join(f'{pad}    "{r}",\n' for r in rows) + f"{pad}]"


def rgba_hex(c):
    return "0x%02X%02X%02X%02X" % c


def emit_swift():
    lines = [
        "// Generated by scripts/sprites.py - edit the art there and re-run it.",
        "// All artwork is original to Thicket.",
        "",
        "public enum SpriteData {",
        "    public static let sprites: [String: [String]] = [",
    ]
    for name in sorted(SPRITES):
        lines.append(f'        "{name}": ' + swift_string_list(SPRITES[name], 8) + ",")
    lines.append("    ]")
    lines.append("")
    lines.append("    /// 5x7 bitmap font.")
    lines.append("    public static let font: [Character: [String]] = [")
    for ch in sorted(FONT):
        esc = ch.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'        "{esc}": ' + swift_string_list(FONT[ch], 8) + ",")
    lines.append("    ]")
    lines.append("")
    lines.append("    /// RGBA (0xRRGGBBAA) for fixed palette keys.")
    lines.append("    public static let palette: [Character: UInt32] = [")
    for k in sorted(PALETTE):
        lines.append(f'        "{k}": {rgba_hex(PALETTE[k])},')
    lines.append("    ]")
    lines.append("")
    lines.append("    /// RGBA for the piece keys 1 (main), 2 (shade), 3 (highlight), by color name.")
    lines.append("    public static let pieceColors: [String: [Character: UInt32]] = [")
    for name in ["ember", "tide", "bloom"]:
        inner = ", ".join(f'"{k}": {rgba_hex(v)}' for k, v in sorted(PIECE_COLORS[name].items()))
        lines.append(f'        "{name}": [{inner}],')
    lines.append("    ]")
    lines.append("}")
    path = os.path.join(ROOT, "Sources/ThicketKit/SpriteData.swift")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", path)


# ---------------------------------------------------------------- App icon

def write_png(path, w, h, pixels):
    raw = b"".join(b"\x00" + bytes(pixels[y * w * 4:(y + 1) * w * 4]) for y in range(h))

    def chunk(t, d):
        c = struct.pack(">I", len(d)) + t + d
        return c + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)

    png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(png)


def emit_icon():
    # 32x32 art canvas scaled 32x to 1024: a Tide Mite and an Ember Seed in the thicket.
    W = 32
    canvas = [[(0x24, 0x3B, 0x2E, 255)] * W for _ in range(W)]
    for y in range(W):  # soft vertical gradient
        t = y / (W - 1)
        col = (int(0x2B + 0x18 * t), int(0x4A + 0x10 * t), int(0x36 + 0x06 * t), 255)
        canvas[y] = [col] * W

    def blit(name, ox, oy, colors=None):
        for y, row in enumerate(SPRITES[name]):
            for x, k in enumerate(row):
                if k == ".":
                    continue
                c = (colors or {}).get(k) or PALETTE.get(k)
                if c and 0 <= ox + x < W and 0 <= oy + y < W:
                    canvas[oy + y][ox + x] = c

    for x in range(0, W, 16):
        blit("canopy", x, 0)
    for x in range(0, W, 16):
        blit("ground", x, 24)
    blit("mite_tide", 2, 9, PIECE_COLORS["tide"])
    blit("seed_ember", 15, 9, PIECE_COLORS["ember"])
    scale = 32
    size = W * scale
    px = bytearray(size * size * 4)
    for y in range(size):
        row = canvas[y // scale]
        for x in range(size):
            c = row[x // scale]
            i = (y * size + x) * 4
            px[i:i + 3] = bytes(c[:3])
            px[i + 3] = 255  # icons must be opaque
    write_png(os.path.join(ROOT, "App/Assets.xcassets/AppIcon.appiconset/icon-1024.png"), size, size, px)
    print("wrote app icon")


if __name__ == "__main__":
    emit_swift()
    emit_icon()
