SPRITES = {}


def sprite(name, rows, width=16, height=16):
    rows = [r.rstrip() for r in rows.strip("\n").split("\n")]
    if len(rows) != height:
        sys.exit(f"{name}: {len(rows)} rows, expected {height}")
    out = []
    for i, r in enumerate(rows):
        if len(r) > width:
            sys.exit(f"{name} row {i}: {len(r)} > {width}: '{r}'")
        out.append(r.ljust(width, "."))
    SPRITES[name] = out


